_FALLBACK = _FONT["?"]


def glyph(char: str) -> tuple[int, ...]:
    """Row masks for a character, falling back to '?' for anything unmapped."""
    return _FONT.get(char.upper(), _FALLBACK)


def text_width(text: str) -> int:
    """Rendered width in pixels, excluding the trailing inter-glyph gap."""
    if not text:
        return 0
    return len(text) * ADVANCE - 1
